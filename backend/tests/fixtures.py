def strava_activities() -> list[dict[str, Any]]:
    """Expand the compact table into Strava v3 summary payloads."""
    out = []
    for sid, sport, start, dist, moving, elapsed, elev, cal, max_speed in RAW:
        local = datetime.fromisoformat(start)
        # Magdeburg is UTC+2 in this period.
        utc = local - timedelta(hours=2)
        payload: dict[str, Any] = {
            "id": sid,
            "name": f"{sport} {sid}",
            "sport_type": sport,
            "type": sport,
            "start_date_local": local.isoformat(),
            "start_date": utc.isoformat() + "Z",
            "distance": dist,
            "moving_time": moving,
            "elapsed_time": elapsed,
            "total_elevation_gain": elev,
            "average_speed": (dist / moving) if moving else 0.0,
            "max_speed": max_speed,
            "has_heartrate": False,
            "device_watts": sport == "Run",
            "achievement_count": 0,
            "pr_count": 0,
        }
        if cal is not None:
            payload["calories"] = cal
        return_efforts = BEST_EFFORTS.get(sid)
        if return_efforts:
            payload["best_efforts"] = [
                {"id": i, "name": name, "moving_time": secs, "elapsed_time": secs}
                for i, (name, secs) in enumerate(return_efforts, start=1)
            ]
        out.append(payload)
    return out
